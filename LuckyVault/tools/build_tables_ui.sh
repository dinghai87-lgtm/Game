#!/bin/bash
# Rebuild js/tables-ui.js from js/tables/*.js (name order) and syntax-check it.
set -e
cd "$(dirname "$0")/.."
{ echo "// GENERATED by tools/build_tables_ui.sh from js/tables/*.js - edit those files, not this one."; cat js/tables/[0-9]*.js; } > js/tables-ui.js.tmp
node -e "new Function(require('fs').readFileSync('js/tables-ui.js.tmp','utf8'))"
mv js/tables-ui.js.tmp js/tables-ui.js
echo "tables-ui.js rebuilt from $(ls js/tables/[0-9]*.js | wc -l) parts"
